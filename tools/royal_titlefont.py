def title_glyph(ch):
    """Interface compatible avec royal_art.fancy_text(font=...)."""
    if ch == " ": return None, 8, 0, 15
    rows = G[ch.upper()]
    a = np.array([[c == "#" for c in r] for r in rows], bool)
    return a, a.shape[1] + 2, 0, 15
